// Initialize Database
function initDB() {
    if (!localStorage.getItem('yatri_products') || !localStorage.getItem('yatri_v7')) {
        localStorage.setItem('yatri_products', JSON.stringify(defaultProducts));
        localStorage.setItem('yatri_v7', 'true');

        // Also update any stale ₹1 items in existing user cart to ₹999
        try {
            const existingCart = JSON.parse(localStorage.getItem('yatri_cart')) || [];
            if (existingCart.length > 0) {
                const updatedCart = existingCart.map(item => {
                    const fresh = defaultProducts.find(p => String(p.id) === String(item.id));
                    if (fresh) {
                        return { ...item, name: fresh.name, price: fresh.price, image: fresh.image };
                    }
                    return item;
                });
                localStorage.setItem('yatri_cart', JSON.stringify(updatedCart));
            }
        } catch (e) {
            console.error('Cart sync error:', e);
        }
    }

    if (!localStorage.getItem('yatri_cart')) {
        localStorage.setItem('yatri_cart', JSON.stringify([]));
    }
    if (!localStorage.getItem('yatri_orders')) {
        localStorage.setItem('yatri_orders', JSON.stringify([]));
    }
}

// Helper to get plain-text summary for product cards
function getCardSummary(product) {
    if (product.shortDescription) return product.shortDescription;
    if (!product.description) return '';
    return product.description.replace(/<[^>]*>/g, ' ').replace(/\s+/g, ' ').trim();
}

// Get All Products
function getProducts() {
    return JSON.parse(localStorage.getItem('yatri_products')) || defaultProducts;
}

// Get Unique Categories Dynamically (with cover image & count)
function getCategories() {
    const products = getProducts();
    const categoryMap = new Map();

    products.forEach(p => {
        const cat = (p.category || 'Other').trim();
        if (!categoryMap.has(cat)) {
            categoryMap.set(cat, {
                name: cat,
                image: categoryCoverImages[cat] || p.image || 'assets/products/backpack-1.jpg',
                count: 1
            });
        } else {
            categoryMap.get(cat).count += 1;
        }
    });

    return Array.from(categoryMap.values());
}

// Get Product By ID
function getProductById(id) {
    const products = getProducts();
    return products.find(p => String(p.id) === String(id));
}

// Get Trending Products
function getTrendingProducts() {
    const products = getProducts();
    return products.filter(p => p.isTrending);
}

// Add to Cart
function addToCart(productId, quantity = 1) {
    const cart = JSON.parse(localStorage.getItem('yatri_cart')) || [];
    const product = getProductById(productId);
    
    const existingItem = cart.find(item => String(item.id) === String(productId));
    if (existingItem) {
        existingItem.quantity += parseInt(quantity);
    } else if (product) {
        cart.push({
            id: product.id,
            name: product.name,
            price: product.price,
            image: product.image,
            quantity: parseInt(quantity)
        });
    }
    
    localStorage.setItem('yatri_cart', JSON.stringify(cart));
    updateCartCount();

    // Meta Pixel AddToCart event
    try {
        if (typeof fbq === 'function' && product) {
            fbq('track', 'AddToCart', {
                content_name: product.name,
                content_category: product.category || 'Luggage',
                content_ids: [String(productId)],
                content_type: 'product',
                value: product.price * parseInt(quantity),
                currency: 'INR'
            });
        }
    } catch (e) {
        console.error('Meta Pixel AddToCart Error:', e);
    }
}

// Buy Now
function buyNow(productId, quantity = 1) {
    addToCart(productId, quantity);
    window.location.href = 'checkout.html';
}

// Update Cart Count UI
function updateCartCount() {
    const cart = JSON.parse(localStorage.getItem('yatri_cart')) || [];
    const count = cart.reduce((total, item) => total + item.quantity, 0);
    const countElements = document.querySelectorAll('.cart-count');
    countElements.forEach(el => el.textContent = count);
}

// Initialize on load
initDB();
window.addEventListener('DOMContentLoaded', updateCartCount);
